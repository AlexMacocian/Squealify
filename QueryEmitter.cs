using Squealify.Model;
using Sybil;
using System.Collections.Generic;
using System.Linq;

namespace Squealify;

/// <summary>
/// Emits the implementations of the [SqlQuery] methods of one class. Built with Sybil syntax builders.
/// </summary>
/// <remarks>
/// Per method: SQL constants, one command cached for the lifetime of the context with parameters created once, and for
/// object rows the column ordinals resolved by name on first execution.
/// </remarks>
internal sealed class QueryEmitter(string @namespace, string className, IReadOnlyList<QueryMethodModel> methods, GenerationOptions options)
{
    private const string ConfigureAwait = ".ConfigureAwait(false)";
    private const string DialectType = "global::Squealify.SqlDialect";

    private readonly string @namespace = @namespace;
    private readonly string className = className;
    private readonly IReadOnlyList<QueryMethodModel> methods = methods;
    private readonly GenerationOptions options = options;

    public string HintName => $"{this.@namespace}.{this.className}.SqlQueries.g.cs";

    public string Emit()
    {
        var classBuilder = SyntaxBuilder.CreateClass(this.className).WithModifiers("partial");
        var keys = new Dictionary<string, int>();
        foreach (var method in this.methods)
        {
            keys.TryGetValue(method.Name, out var count);
            keys[method.Name] = count + 1;
            var key = count == 0 ? $"{method.Name}Query" : $"{method.Name}Query{count + 1}";
            this.AddMethod(classBuilder, method, key);
        }

        var namespaceBuilder = this.options.FileScopedNamespace
            ? SyntaxBuilder.CreateFileScopedNamespace(this.@namespace)
            : SyntaxBuilder.CreateNamespace(this.@namespace);

        return SyntaxBuilder.CreateCompilationUnit()
            .WithHeaderComment("<auto-generated/>")
            .WithNullableContext(true)
            .WithUsing("System")
            .WithUsing("System.Collections.Generic")
            .WithUsing("System.Data")
            .WithUsing("System.Data.Common")
            .WithUsing("System.Threading")
            .WithUsing("System.Threading.Tasks")
            .WithNamespace(namespaceBuilder.WithClass(classBuilder))
            .Build()
            .ToFullString();
    }

    private void AddMethod(ClassBuilder classBuilder, QueryMethodModel method, string key)
    {
        var commandField = ToCamelCase(key) + "Command";
        var ordinalsField = ToCamelCase(key) + "Ordinals";
        var membersField = key + "Members";
        var sqlField = key + "Sql";
        var postgreSqlField = key + "PostgreSqlSql";
        var bound = method.Parameters.Where(p => !p.IsCancellationToken).ToList();
        var cancellation = method.Parameters.FirstOrDefault(p => p.IsCancellationToken)?.Name ?? "CancellationToken.None";

        classBuilder
            .WithField(Const(sqlField, Verbatim(method.Sql)))
            .WithField(SyntaxBuilder.CreateField("DbCommand?", commandField).WithModifier(Constants.Private));
        var sqlExpression = sqlField;
        if (method.PostgreSql is not null)
        {
            classBuilder.WithField(Const(postgreSqlField, Verbatim(method.PostgreSql)));
            sqlExpression = $"this.Dialect == {DialectType}.{Constants.SqlDialectPostgreSql} ? {postgreSqlField} : {sqlField}";
        }

        var objectRow = method.Row is { Kind: RowKind.Object };
        if (objectRow)
        {
            var names = string.Join(", ", method.Row!.Members.Select(m => Literal(m.ColumnName)));
            classBuilder
                .WithField(SyntaxBuilder.CreateField("string[]", membersField)
                    .WithModifiers("private static readonly")
                    .WithInitializer($"new string[] {{ {names} }}"))
                .WithField(SyntaxBuilder.CreateField("int[]?", ordinalsField).WithModifier(Constants.Private));
        }

        var addParameters = string.Join("\n", bound.Select(p =>
            $"    command.Parameters.Add(this.CreateParameter<{ColumnCodec.ParameterType(p.Value!)}>(command, {Literal("@" + p.Name.TrimStart('@'))}));"));
        classBuilder.WithMethod(SyntaxBuilder.CreateMethod("DbCommand", $"Get{key}Command")
            .WithModifier(Constants.Private)
            .WithBody($@"var command = this.{commandField};
if (command is null)
{{
    command = this.CreateCachedCommand({sqlExpression});
{addParameters}
    this.{commandField} = command;
}}

command.Transaction = this.Transaction;
return command;"));

        var setParameters = bound.Count == 0
            ? string.Empty
            : "var parameters = command.Parameters;\n" + string.Join("\n", bound.Select((p, i) =>
                $"this.SetParameterValue<{ColumnCodec.ParameterType(p.Value!)}>(parameters[{i}], {ColumnCodec.WriteExpression(p.Value!, p.Name)});"));
        var body = $@"var command = this.Get{key}Command();
{setParameters}
{this.Body(method, cancellation, ordinalsField, membersField)}";

        var modifiers = string.Join(" ", new[] { method.Accessibility, method.IsAsync ? "async" : string.Empty, "partial" }.Where(m => m.Length > 0));
        var implementation = SyntaxBuilder.CreateMethod(method.ReturnType, method.Name).WithModifiers(modifiers);
        foreach (var parameter in method.Parameters)
        {
            implementation.WithParameter(parameter.Type, parameter.Name);
        }

        classBuilder.WithMethod(implementation.WithBody(body));
    }

    private string Body(QueryMethodModel method, string cancellation, string ordinalsField, string membersField)
    {
        switch (method.Shape)
        {
            case QueryShape.Execute:
                return Execute(method, "ExecuteNonQuery", cancellation) + ";";
            case QueryShape.Affected:
                return $"return {Execute(method, "ExecuteNonQuery", cancellation)};";
        }

        var row = method.Row!;
        var openReader = method.IsAsync
            ? $"await using var reader = await command.ExecuteReaderAsync({(method.Shape == QueryShape.Single ? "CommandBehavior.SingleRow, " : string.Empty)}{cancellation}){ConfigureAwait};"
            : $"using var reader = command.ExecuteReader({(method.Shape == QueryShape.Single ? "CommandBehavior.SingleRow" : string.Empty)});";
        var read = method.IsAsync ? $"await reader.ReadAsync({cancellation}){ConfigureAwait}" : "reader.Read()";
        var ordinals = row.Kind == RowKind.Object
            ? $"\nvar ordinals = this.{ordinalsField} ??= ResolveOrdinals(reader, {membersField});"
            : string.Empty;
        var value = RowExpression(row);
        if (method.Shape == QueryShape.List)
        {
            return $@"{openReader}{ordinals}
var results = new List<{row.Declared}>();
while ({read})
{{
    results.Add({value});
}}

return results;";
        }

        var noRow = method.NullableResult
            ? "return null;"
            : $"throw new InvalidOperationException({Literal($"Query '{method.Name}' returned no rows.")});";
        return $@"{openReader}{ordinals}
if (!{read})
{{
    {noRow}
}}

return {value};";
    }

    private static string Execute(QueryMethodModel method, string execute, string cancellation)
        => method.IsAsync ? $"await command.{execute}Async({cancellation}){ConfigureAwait}" : $"command.{execute}()";

    private static string RowExpression(RowModel row)
    {
        switch (row.Kind)
        {
            case RowKind.Scalar:
                return ColumnCodec.ReadExpression(row.Members[0], "0");
            case RowKind.Tuple:
                return "(" + string.Join(", ", row.Members.Select((m, i) => ColumnCodec.ReadExpression(m, i.ToString()))) + ")";
            default:
                var assignments = string.Join(",\n", row.Members.Select((m, i) => $"    {m.PropertyName} = {ColumnCodec.ReadExpression(m, $"ordinals[{i}]")}"));
                return $"new {row.Type}\n{{\n{assignments}\n}}";
        }
    }

    private static FieldBuilder Const(string name, string value)
        => SyntaxBuilder.CreateField("string", name)
            .WithModifiers("private const")
            .WithInitializer(value);

    private static string ToCamelCase(string name)
        => name.Length == 0 ? name : char.ToLowerInvariant(name[0]) + name.Substring(1);

    private static string Literal(string value)
        => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true);

    private static string Verbatim(string value)
        => "@\"" + value.Replace("\"", "\"\"") + "\"";
}

using Microsoft.CodeAnalysis;
using Sybil;

namespace Squealify;

/// <summary>
/// Generates the internal runtime helper used by table contexts to build and cache multi-row statements.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SqlBatchGenerator : IIncrementalGenerator
{
    public const string ClassName = "SqlBatch";
    public const int MaxCachedParameterNames = 1024;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(Generate);
    }

    private static void Generate(IncrementalGeneratorPostInitializationContext context)
    {
        var source = SyntaxBuilder.CreateCompilationUnit()
            .WithHeaderComment("<auto-generated/>")
            .WithNullableContext(true)
            .WithNamespace(SyntaxBuilder.CreateNamespace(Constants.Namespace)
                .WithUsing(Constants.UsingSystem)
                .WithUsing("System.Text")
                .WithClass(SyntaxBuilder.CreateClass(ClassName)
                    .WithModifiers("internal static")
                    .WithField(SyntaxBuilder.CreateField("string[]", "ParameterNames")
                        .WithModifiers("private static readonly")
                        .WithInitializer($"new string[{MaxCachedParameterNames}]"))
                    .WithMethod(SyntaxBuilder.CreateMethod("string", "ParameterName")
                        .WithModifiers("public static")
                        .WithParameter("int", "index")
                        .WithBody(@"if (index >= ParameterNames.Length)
{
    return ""@p"" + index;
}

return ParameterNames[index] ??= ""@p"" + index;"))
                    .WithMethod(SyntaxBuilder.CreateMethod("int", "GetSlot")
                        .WithModifiers("public static")
                        .WithParameter("int", "remaining")
                        .WithParameter("int", "largeRows")
                        .WithParameter("int", "smallRows")
                        .WithExpression("remaining >= largeRows ? 0 : remaining >= smallRows ? 1 : 2"))
                    .WithMethod(SyntaxBuilder.CreateMethod("int", "GetRows")
                        .WithModifiers("public static")
                        .WithParameter("int", "slot")
                        .WithParameter("int", "largeRows")
                        .WithParameter("int", "smallRows")
                        .WithExpression("slot == 0 ? largeRows : slot == 1 ? smallRows : 1"))
                    .WithMethod(SyntaxBuilder.CreateMethod("string", "GetValuesSql")
                        .WithModifiers("public static")
                        .WithParameter("string[]", "cache")
                        .WithParameter("int", "slot")
                        .WithParameter("string", "head")
                        .WithParameter("string", "tail")
                        .WithParameter("int", "rows")
                        .WithParameter("int", "columns")
                        .WithParameter("bool", "parenthesize")
                        .WithBody(@"var sql = cache[slot];
if (sql is null)
{
    sql = BuildValuesSql(head, tail, rows, columns, parenthesize);
    cache[slot] = sql;
}

return sql;"))
                    .WithMethod(SyntaxBuilder.CreateMethod("string", "BuildValuesSql")
                        .WithModifiers("private static")
                        .WithParameter("string", "head")
                        .WithParameter("string", "tail")
                        .WithParameter("int", "rows")
                        .WithParameter("int", "columns")
                        .WithParameter("bool", "parenthesize")
                        .WithBody(@"var builder = new StringBuilder(head.Length + tail.Length + (rows * columns * 7));
builder.Append(head);
for (var row = 0; row < rows; row++)
{
    if (row > 0)
    {
        builder.Append("", "");
    }

    if (parenthesize)
    {
        builder.Append('(');
    }

    for (var column = 0; column < columns; column++)
    {
        if (column > 0)
        {
            builder.Append("", "");
        }

        builder.Append(""@p"").Append((row * columns) + column);
    }

    if (parenthesize)
    {
        builder.Append(')');
    }
}

builder.Append(tail);
return builder.ToString();"))))
            .Build()
            .ToFullString();

        context.AddSource($"{ClassName}.g.cs", source);
    }
}

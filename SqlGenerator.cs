using Squealify.Model;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Squealify;

/// <summary>
/// Builds the SQL text for a table. Statement parameters are named @p0..@pN in the order documented per method.
/// </summary>
internal sealed class SqlGenerator(TableModel table)
{
    private readonly TableModel table = table;

    public string Table => Quote(this.table.TableName);

    public string SelectColumns => string.Join(", ", this.table.Columns.Select(c => Quote(c.ColumnName)));

    public static string Quote(string identifier) => $"\"{identifier.Replace("\"", "\"\"")}\"";

    public string CreateTable(SqlDialect dialect, bool ifNotExists)
    {
        var columns = this.table.Columns;
        var primaryKeys = columns.Where(c => c.IsPrimaryKey).ToList();
        var inlinePrimaryKey = primaryKeys.Count == 1;
        var definitions = new List<string>();
        foreach (var column in columns)
        {
            var definition = new StringBuilder($"    {Quote(column.ColumnName)} ");
            if (column.IsAutoIncrement)
            {
                definition.Append(dialect == SqlDialect.SQLite
                    ? "INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL"
                    : $"{(column.Kind == ColumnKind.Int32 ? "INTEGER" : "BIGINT")} GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
                definitions.Add(definition.ToString());
                continue;
            }

            definition.Append(GetColumnType(column, dialect));
            if (!column.IsNullable || column.IsPrimaryKey)
            {
                definition.Append(" NOT NULL");
            }

            if (column.IsPrimaryKey && inlinePrimaryKey)
            {
                definition.Append(" PRIMARY KEY");
            }

            if (column.IsUnique)
            {
                definition.Append(" UNIQUE");
            }

            definitions.Add(definition.ToString());
        }

        if (!inlinePrimaryKey && primaryKeys.Count > 0)
        {
            definitions.Add($"    PRIMARY KEY ({ColumnList(primaryKeys)})");
        }

        foreach (var keySet in this.table.KeySets.Where(k => k.IsUnique))
        {
            if (keySet.Columns.Length == 1 && columns[keySet.Columns[0]].IsUnique)
            {
                continue;
            }

            definitions.Add($"    UNIQUE ({ColumnList(keySet.Columns.Select(i => columns[i]))})");
        }

        foreach (var foreignKey in this.table.ForeignKeys)
        {
            var onDelete = foreignKey.OnDelete switch
            {
                1 => " ON DELETE CASCADE",
                2 => " ON DELETE SET NULL",
                3 => " ON DELETE RESTRICT",
                4 => " ON DELETE SET DEFAULT",
                _ => string.Empty
            };

            definitions.Add(
                $"    FOREIGN KEY ({ColumnList(foreignKey.Columns.Select(i => columns[i]))}) " +
                $"REFERENCES {Quote(foreignKey.ReferenceTable)} ({string.Join(", ", foreignKey.ReferenceColumns.Select(Quote))}){onDelete}");
        }

        var ifNotExistsText = ifNotExists ? "IF NOT EXISTS " : string.Empty;
        var builder = new StringBuilder()
            .Append($"CREATE TABLE {ifNotExistsText}{this.Table} (\n")
            .Append(string.Join(",\n", definitions))
            .Append("\n);");

        foreach (var keySet in this.table.KeySets.Where(k => k.CreateIndex))
        {
            var keyColumns = keySet.Columns.Select(i => columns[i]).ToList();
            var indexName = Quote($"ix_{this.table.TableName}_{string.Join("_", keyColumns.Select(c => c.ColumnName))}");
            builder.Append($"\nCREATE INDEX {ifNotExistsText}{indexName} ON {this.Table} ({ColumnList(keyColumns)});");
        }

        return builder.ToString();
    }

    /// <summary>
    /// Head of a multi-row INSERT; rows of @p parameters follow.
    /// </summary>
    public string ValuesHead(IEnumerable<ColumnModel> columns)
        => $"INSERT INTO {this.Table} ({ColumnList(columns)})\nVALUES ";

    public string UpsertTail()
    {
        var keys = this.table.Columns.Where(c => c.IsPrimaryKey).ToList();
        var nonKeys = this.table.Columns.Where(c => !c.IsPrimaryKey).ToList();
        if (nonKeys.Count == 0)
        {
            return $"\nON CONFLICT ({ColumnList(keys)}) DO NOTHING;";
        }

        var assignments = string.Join(",\n    ", nonKeys.Select(c => $"{Quote(c.ColumnName)} = excluded.{Quote(c.ColumnName)}"));
        return $"\nON CONFLICT ({ColumnList(keys)}) DO UPDATE SET\n    {assignments};";
    }

    /// <summary>
    /// Parameters: the given columns, in order. Returns the auto increment column.
    /// </summary>
    public string InsertReturning(IReadOnlyList<ColumnModel> columns, ColumnModel autoIncrement)
        => columns.Count == 0
            ? $"INSERT INTO {this.Table}\nDEFAULT VALUES\nRETURNING {Quote(autoIncrement.ColumnName)};"
            : $"INSERT INTO {this.Table} ({ColumnList(columns)})\nVALUES ({ParameterList(0, columns.Count)})\nRETURNING {Quote(autoIncrement.ColumnName)};";

    /// <summary>
    /// Parameters: non key columns, then key columns.
    /// </summary>
    public string Update(IReadOnlyList<ColumnModel> nonKeys, IReadOnlyList<ColumnModel> keys)
    {
        var assignments = string.Join(",\n    ", nonKeys.Select((c, i) => $"{Quote(c.ColumnName)} = @p{i}"));
        return $"UPDATE {this.Table} SET\n    {assignments}\nWHERE {Where(keys, nonKeys.Count)};";
    }

    public string Delete(IReadOnlyList<ColumnModel> keys) => $"DELETE FROM {this.Table}\nWHERE {Where(keys, 0)};";

    public string DeleteManyHead(IReadOnlyList<ColumnModel> keys)
        => keys.Count == 1
            ? $"DELETE FROM {this.Table}\nWHERE {Quote(keys[0].ColumnName)} IN ("
            : $"DELETE FROM {this.Table}\nWHERE ({ColumnList(keys)}) IN (VALUES ";

    public string DeleteAll() => $"DELETE FROM {this.Table};";

    public string Select(IReadOnlyList<ColumnModel> filter)
        => filter.Count == 0
            ? $"SELECT {this.SelectColumns}\nFROM {this.Table};"
            : $"SELECT {this.SelectColumns}\nFROM {this.Table}\nWHERE {Where(filter, 0)};";

    public static string GetColumnType(ColumnModel column, SqlDialect dialect)
    {
        var sqlite = dialect == SqlDialect.SQLite;
        return column.Kind switch
        {
            ColumnKind.Boolean => "BOOLEAN",
            ColumnKind.Byte or ColumnKind.SByte or ColumnKind.Int16 => "SMALLINT",
            ColumnKind.UInt16 or ColumnKind.Int32 => "INTEGER",
            ColumnKind.UInt32 or ColumnKind.Int64 or ColumnKind.UInt64 => "BIGINT",
            ColumnKind.Single => "REAL",
            ColumnKind.Double => sqlite ? "REAL" : "DOUBLE PRECISION",
            ColumnKind.Decimal => sqlite ? "TEXT" : "NUMERIC",
            ColumnKind.String when column.VarcharLength is int length => $"VARCHAR({length})",
            ColumnKind.Guid => sqlite ? "BLOB" : "UUID",
            ColumnKind.DateTime or ColumnKind.DateTimeOffset => sqlite ? "TEXT" : "TIMESTAMPTZ",
            ColumnKind.DateOnly => sqlite ? "TEXT" : "DATE",
            ColumnKind.TimeOnly => sqlite ? "TEXT" : "TIME",
            ColumnKind.TimeSpan => sqlite ? "TEXT" : "INTERVAL",
            ColumnKind.Bytes => sqlite ? "BLOB" : "BYTEA",
            _ => "TEXT"
        };
    }

    private static string Where(IReadOnlyList<ColumnModel> columns, int parameterOffset)
        => string.Join(" AND ", columns.Select((c, i) => $"{Quote(c.ColumnName)} = @p{parameterOffset + i}"));

    private static string ColumnList(IEnumerable<ColumnModel> columns) => string.Join(", ", columns.Select(c => Quote(c.ColumnName)));

    private static string ParameterList(int offset, int count) => string.Join(", ", Enumerable.Range(offset, count).Select(i => $"@p{i}"));
}

internal enum SqlDialect
{
    SQLite,
    PostgreSQL
}
